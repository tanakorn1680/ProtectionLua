function BottomNav() {
  const pathname = usePathname()
  const { signOut } = useAdmin()

  const allItems = [
    ...NAV_ITEMS,
    {
      href: '#logout',
      label: 'ออก',
      icon: (
        <svg className="w-5 h-5" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={1.5}>
          <path strokeLinecap="round" strokeLinejoin="round" d="M15.75 9V5.25A2.25 2.25 0 0013.5 3h-6a2.25 2.25 0 00-2.25 2.25v13.5A2.25 2.25 0 007.5 21h6a2.25 2.25 0 002.25-2.25V15m3 0l3-3m0 0l-3-3m3 3H9" />
        </svg>
      ),
    },
  ]

  return (
    <nav className="fixed bottom-0 inset-x-0 bg-surface-card border-t border-surface-border lg:hidden z-30">
      <div className="flex">
        {allItems.map(item => {
          const active = item.href !== '#logout' && pathname.startsWith(item.href)
          if (item.href === '#logout') {
            return (
              <button
                key="logout"
                onClick={signOut}
                className="flex-1 flex flex-col items-center gap-1 py-3 text-gray-500 hover:text-red-400 transition-colors"
              >
                {item.icon}
                <span className="text-[10px]">{item.label}</span>
              </button>
            )
          }
          return (
            <Link
              key={item.href}
              href={item.href}
              className={`flex-1 flex flex-col items-center gap-1 py-3 transition-colors ${
                active ? 'text-accent' : 'text-gray-500 hover:text-white'
              }`}
            >
              {item.icon}
              <span className="text-[10px]">{item.label}</span>
            </Link>
          )
        })}
      </div>
    </nav>
  )
}

function AdminShell({ children }: { children: React.ReactNode }) {
  const { loading } = useAdmin()

  if (loading) {
    return (
      <div className="min-h-screen flex items-center justify-center bg-surface">
        <div className="w-5 h-5 border-2 border-accent/30 border-t-accent rounded-full animate-spin" />
      </div>
    )
  }

  return (
    <div className="min-h-screen bg-surface">
      <Sidebar />
      <BottomNav />
      <main className="lg:pl-56 pb-20 lg:pb-0">
        <div className="max-w-5xl mx-auto p-4 lg:p-6">
          {children}
        </div>
      </main>
    </div>
  )
}

export default function AdminLayout({ children }: { children: React.ReactNode }) {
  return (
    <AdminProvider>
      <AdminShell>{children}</AdminShell>
    </AdminProvider>
  )
}
